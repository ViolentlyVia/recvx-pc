"""Generate pc/src/pc_stubs.c: placeholder definitions for every symbol the link still misses.

Run after a build that failed only with unresolved externals. Each stub logs its first call, so
the log shows which unported PS2 functions the game actually reaches. Delete a stub from the
generated file's input (by implementing the symbol elsewhere) and regenerate.
"""
import os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
import common

OUT = os.path.join(common.ROOT, "pc/src/pc_stubs.c")
HEADERS = ["ps2_dummy.h", "ps2_loadtim2.h", "ps2_NaDraw2D.h", "ps2_NaSprite.h", "ps2_NaSystem.h",
           "ps2_NinjaCnk.h", "ps2_Vu1Strip.h", "ps2_MovieFunc.h", "sub1.h", "main.h"]
CRI_HEADERS = ["htci.h", "htci_sub.h"]


def main():
    # build without the old stubs to see everything that is missing
    if os.path.exists(OUT):
        os.remove(OUT)
    subprocess.run([sys.executable, os.path.join(os.path.dirname(__file__), "build.py")])
    syms = open(os.path.join(common.BUILD, "unresolved.txt")).read().split()
    out = subprocess.run([sys.executable, os.path.join(os.path.dirname(__file__), "find_decls.py")] + syms,
                         capture_output=True, text=True).stdout.splitlines()

    lines = ["/* GENERATED by pc/tools/gen_stubs.py - placeholders for unported PS2 code. */"]
    lines += ['#include "../../include/ps2/veronica/prog/%s"' % h for h in HEADERS]
    lines += ['#include "../../include/cri/mwlib/ee/lib/libadxe/%s"' % h for h in CRI_HEADERS]
    lines += ['#include "pc_platform.h"', "",
              '#define PC_STUB() do { static int once; if (!once) { once = 1; pcLog("stub: %s", __func__); } } while (0)',
              ""]
    missing = []
    for row in out:
        sym, decl = row[:36].strip(), row[37:].strip()
        if sym == "asm" or decl == "-" or ": " not in decl:
            missing.append(sym)
            continue
        decl = decl.split(": ", 1)[1].rstrip(";").strip()
        if decl.startswith("extern"):
            lines.append(decl[len("extern"):].strip() + ";")
            continue
        m = re.match(r"(.*?)\b%s\s*\((.*)\)$" % re.escape(sym), decl)
        if not m:
            missing.append(sym)
            continue
        ret, params = m.group(1).strip(), m.group(2).strip()
        # name unnamed parameters (C17 requires names in definitions)
        if params not in ("", "void"):
            ps = []
            for i, p in enumerate(params.split(",")):
                p = p.strip()
                if not re.search(r"[A-Za-z_]\w*\s*(\[.*\])?$", p) or re.fullmatch(
                        r"(const\s+)?(unsigned\s+|signed\s+)?(int|char|short|long|float|void\s*\*|Int|Sint32|Uint32|Float|Bool|Angle|u_int)\s*\**", p):
                    p = p + " a%d" % i
                ps.append(p)
            params = ", ".join(ps)
        body = "    PC_STUB();\n"
        if ret not in ("void",):
            body += "    return 0;\n"
        lines.append("%s %s(%s)\n{\n%s}\n" % (ret, sym, params or "void", body))
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    if missing:
        print("no declaration found (add by hand):", " ".join(missing))


if __name__ == "__main__":
    main()
